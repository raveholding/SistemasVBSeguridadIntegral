"""
Prueba en navegador de lo traído del Portero Cannabismática:
doble toque para el panel, puesta en marcha, personas con PIN propio, horario de atención,
huella con passkeys (autenticador virtual de Chromium), rostro (carga de modelos),
lector QR USB tipo teclado, pases con usos y vista móvil.

Uso:  python3 tests/e2e_accesos.py      (solo requiere Node.js y Playwright; no usa go2rtc)
"""
import os, socket, subprocess, sys, tempfile, time
from playwright.sync_api import sync_playwright
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SHOTS = os.path.join(ROOT, 'tests', 'screenshots'); os.makedirs(SHOTS, exist_ok=True)
s = socket.socket(); s.bind(('127.0.0.1', 0)); PORT = s.getsockname()[1]; s.close()
tmp = tempfile.mkdtemp(prefix='svb-e2e-'); open(os.path.join(tmp, '.env'), 'w').close()
env = {**os.environ, 'PORT': str(PORT), 'HOST': '127.0.0.1', 'GO2RTC_DISABLED': '1', 'DATA_DIR': os.path.join(tmp, 'data'), 'DOORBELL': '0', 'TELEGRAM_POLL': '0', 'PUSH_ENABLED': '0', 'SVB_ENV_FILE': os.path.join(tmp, '.env')}
srv = subprocess.Popen(['node', 'server.js'], cwd=os.path.join(ROOT, 'server'), env=env, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
time.sleep(1.5)
URL = f'http://localhost:{PORT}/'
import urllib.request as _u; _u.urlopen(_u.Request(URL + 'api/v1/wizard', data=b'{"done":true}', headers={'Content-Type':'application/json','X-Admin-Pin':'1234'}, method='POST'), timeout=10).read()  # asistente ya completado (prueba de la instalación de fábrica en e2e_instalacion.py)
errs = []
ok = []
def check(name, cond, extra=''):
    ok.append((name, bool(cond))); print(('✔' if cond else '✘'), name, extra if not cond else '')
with sync_playwright() as p:
    b = p.chromium.launch(args=['--use-fake-ui-for-media-stream', '--use-fake-device-for-media-stream', '--autoplay-policy=no-user-gesture-required'])
    ctx = b.new_context(viewport={'width': 1366, 'height': 820}, permissions=['camera', 'microphone'])
    pg = ctx.new_page()
    pg.on('console', lambda m: errs.append(m.text) if m.type == 'error' else None)
    pg.on('pageerror', lambda e: errs.append('PAGEERROR ' + str(e)))
    cdp = ctx.new_cdp_session(pg)
    cdp.send('WebAuthn.enable')
    auth = cdp.send('WebAuthn.addVirtualAuthenticator', {'options': {'protocol': 'ctap2', 'transport': 'internal', 'hasResidentKey': True, 'hasUserVerification': True, 'isUserVerified': True, 'automaticPresenceSimulation': True}})
    pg.goto(URL); pg.wait_for_timeout(2500)
    check('pill horario', pg.locator('#stHours').inner_text().strip() == 'Abierto 24 h', pg.locator('#stHours').inner_text())
    pg.screenshot(path=SHOTS + '/01-inicio.png')
    # doble toque en zona libre (pantalla de la puerta)
    bx = pg.locator('#doorScreen').bounding_box()
    x, y = bx['x'] + bx['width'] / 2, bx['y'] + bx['height'] / 2
    pg.mouse.click(x, y); pg.wait_for_timeout(120); pg.mouse.click(x, y); pg.wait_for_timeout(200)
    check('doble toque abre PIN admin', pg.locator('#pinOv').is_visible())
    # toque inmediato: no debe sumar dígitos (clic fantasma)
    pg.locator('#adminKeys [data-k="5"]').click(); pg.wait_for_timeout(500)
    check('toque fantasma ignorado', pg.locator('#adminDisplay .dot.f').count() == 0)
    for k in '1234': pg.locator(f'#adminKeys [data-k="{k}"]').click()
    pg.locator('#adminKeys [data-k="OK"]').click(); pg.wait_for_timeout(1200)
    check('panel admin abierto', pg.locator('#adminOv').is_visible())
    pg.wait_for_timeout(800)
    check('puesta en marcha visible', 'Puesta en marcha' in pg.locator('#setupCheck').inner_text())
    pg.screenshot(path=SHOTS + '/02-puesta-en-marcha.png')
    # personas
    pg.locator('#adminNav [data-go="personas"]').click()
    pg.fill('#npName', 'Juan'); pg.fill('#npPin', '4321'); pg.locator('#npAdd').click(); pg.wait_for_timeout(900)
    pg.fill('#npName', 'Distribuidora Norte'); pg.select_option('#npRole', 'Proveedor'); pg.fill('#npPin', '7777'); pg.locator('#npAdd').click(); pg.wait_for_timeout(900)
    check('2 personas cargadas', pg.locator('#peopleBox .person').count() == 2)
    # PIN duplicado rechazado
    card = pg.locator('#peopleBox .person').nth(1)
    card.locator('[data-pf="pin"]').fill('4321'); card.locator('[data-pact="save"]').click(); pg.wait_for_timeout(700)
    check('PIN duplicado rechazado', 'otra persona' in card.inner_text())
    pg.screenshot(path=SHOTS + '/03-personas.png', full_page=True)
    # horario: lunes a sábado 9-13 y 17-21, guardar
    pg.locator('#adminNav [data-go="horario"]').click(); pg.wait_for_timeout(500)
    pg.select_option('#hMode', 'sched'); pg.wait_for_timeout(200)
    pg.locator('[data-h="add"][data-d="1"]').click(); pg.wait_for_timeout(100)
    pg.locator('[data-hs="1:0:to"]').fill('13:00'); pg.locator('[data-hs="1:0:to"]').dispatch_event('change')
    pg.locator('[data-h="add"][data-d="1"]').click()
    pg.locator('[data-h="copyall"]').click()
    pg.locator('[data-h="del"][data-d="0"][data-i="1"]').click(); pg.locator('[data-h="del"][data-d="0"][data-i="0"]').click()
    pg.locator('#hSave').click(); pg.wait_for_timeout(800)
    txt = pg.locator('#hoursForm').inner_text()
    check('horario guardado', 'Guardado' in txt and 'Lun a Sáb · 09:00 a 13:00 h y 17:00 a 21:00 h' in txt, txt[:300])
    pg.screenshot(path=SHOTS + '/04-horario.png', full_page=True)
    # cerrar manualmente
    pg.select_option('#hMode', 'off'); pg.locator('#hSave').click(); pg.wait_for_timeout(800)
    # biometría: consentimiento + huella de este equipo
    pg.locator('#adminNav [data-go="bio"]').click(); pg.wait_for_timeout(600)
    pg.locator('#bioBox [data-pid] [data-bconsent]').first.check(); pg.wait_for_timeout(900)
    pg.locator('#bioBox [data-bact="pkdev"]').first.click(); pg.wait_for_timeout(2500)
    check('huella registrada', 'Huella · Dispositivo' in pg.locator('#bioBox').inner_text(), pg.locator('#bioBox').inner_text()[:400])
    pg.locator('#bPk').check(); pg.wait_for_timeout(700)
    pg.locator('#bFace').check(); pg.wait_for_timeout(700)
    pg.wait_for_timeout(500)
    check('modelo facial disponible', 'Modelo de reconocimiento disponible' in pg.locator('#faceModel').inner_text())
    pg.screenshot(path=SHOTS + '/05-huella-rostro.png', full_page=True)
    pg.locator('#adminNav [data-go="soporte"]').click(); pg.wait_for_timeout(300)
    pg.screenshot(path=SHOTS + '/06-soporte.png')
    pg.locator('#adminClose').click(); pg.wait_for_timeout(1500)
    # pantalla principal cerrada
    check('pill Cerrado', pg.locator('#stHours').inner_text().strip() == 'Cerrado')
    check('botón huella visible', pg.locator('#btnPk').is_visible())
    pg.screenshot(path=SHOTS + '/07-cerrado.png')
    pg.locator('#btnRing').click(); pg.wait_for_timeout(300)
    check('timbre fuera de horario', 'FUERA DE HORARIO' in pg.locator('#flashTitle').inner_text())
    pg.screenshot(path=SHOTS + '/08-fuera-de-horario.png')
    pg.wait_for_timeout(4200)
    # empleado con PIN fuera de horario: entra (staffOff)
    for k in '4321': pg.keyboard.press(k)
    pg.keyboard.press('Enter'); pg.wait_for_timeout(700)
    check('empleado entra fuera de horario', pg.locator('#flashSub').inner_text() == 'Bienvenido/a, Juan', pg.locator('#flashSub').inner_text())
    pg.wait_for_timeout(2500)
    for k in '7777': pg.keyboard.press(k)
    pg.keyboard.press('Enter'); pg.wait_for_timeout(700)
    check('proveedor bloqueado fuera de horario', 'FUERA DE HORARIO' in pg.locator('#flashTitle').inner_text())
    pg.wait_for_timeout(4200)
    # huella
    pg.locator('#btnPk').click(); pg.wait_for_timeout(2500)
    check('huella abre la puerta', pg.locator('#flashSub').inner_text() == 'Bienvenido/a, Juan', pg.locator('#flashTitle').inner_text() + ' / ' + pg.locator('#flashSub').inner_text())
    pg.wait_for_timeout(2500)
    # lector QR tipo teclado con pase (abrimos el horario primero)
    r = pg.evaluate("""async () => { net.adminPin='1234'; await api('/api/hours',{method:'PUT',admin:true,body:{mode:'always'}}); const v = await api('/api/visitors',{method:'POST',admin:true,body:{name:'Coca-Cola',hours:2,max:1}}); await refreshStatus(); return v; }""")
    pg.wait_for_timeout(500)
    pg.keyboard.type(f"SVB1|{r['code']}|2026|Coca-Cola", delay=5); pg.keyboard.press('Enter'); pg.wait_for_timeout(800)
    check('lector QR USB abre con pase', pg.locator('#flashSub').inner_text() == 'Bienvenido/a, Coca-Cola', pg.locator('#flashSub').inner_text())
    pg.wait_for_timeout(2500)
    pg.keyboard.type(f"SVB1|{r['code']}|2026|Coca-Cola", delay=5); pg.keyboard.press('Enter'); pg.wait_for_timeout(800)
    check('pase de 1 uso se agota', pg.locator('#flashTitle').inner_text() == 'ACCESO DENEGADO', pg.locator('#flashTitle').inner_text())
    pg.wait_for_timeout(2500)
    # rostro: abre la cámara y carga modelos (la cámara simulada no tiene cara)
    check('botón rostro oculto sin rostros cargados', not pg.locator('#btnFace').is_visible()); pg.evaluate('() => { faceRecognize(); }'); pg.wait_for_timeout(6000)
    check('rostro: overlay y modelos cargados', pg.locator('#faceOv').is_visible() and 'Cargando' not in pg.locator('#faceSub').inner_text(), pg.locator('#faceSub').inner_text())
    pg.screenshot(path=SHOTS + '/09-rostro.png')
    pg.locator('#faceCancel').click(); pg.wait_for_timeout(300)
    check('rostro cancelado', not pg.locator('#faceOv').is_visible())
    # móvil
    m = b.new_context(viewport={'width': 390, 'height': 844}, is_mobile=True, has_touch=True)
    mp = m.new_page(); mp.on('pageerror', lambda e: errs.append('M ' + str(e)))
    mp.goto(URL); mp.wait_for_timeout(2000)
    mp.screenshot(path=SHOTS + '/10-movil.png', full_page=True)
    mp.locator('.ticker').scroll_into_view_if_needed(); mp.wait_for_timeout(300)
    bx = mp.locator('.ticker').bounding_box()
    mp.touchscreen.tap(bx['x'] + 40, bx['y'] + 10); mp.wait_for_timeout(150); mp.touchscreen.tap(bx['x'] + 40, bx['y'] + 10); mp.wait_for_timeout(300)
    check('móvil: doble toque abre PIN', mp.locator('#pinOv').is_visible())
    b.close()
print('ERRORES CONSOLA:', [e for e in errs if 'favicon' not in e][:10])
print('RESULTADO', sum(1 for _, c in ok if c), '/', len(ok))
srv.terminate()
sys.exit(0 if all(c for _, c in ok) else 1)
